#!/usr/bin/env node
/**
 * Wave 3 Option B — sync / verify countryPricing seed + core exports.
 *
 * Canonical: Ondial_Webhook/lib/countryPricing.js
 *
 * Usage:
 *   node scripts/sync-pricing-module.js            # verify only (exit 1 on seed drift)
 *   node scripts/sync-pricing-module.js --apply    # write seed snapshot + update hash file
 *   node scripts/sync-pricing-module.js --check-ci # same as verify (for CI)
 *
 * Does NOT blindly overwrite ESM loaders in other repos (preserve export shape).
 * Instead: compares DEFAULT_COUNTRY_PRICING JSON + DEFAULT_FALLBACK_ORDER across repos,
 * writes docs/PRICING_MODULE_CANONICAL_HASH.txt, and optionally refreshes
 * `countryPricing.seed.json` snapshots next to each copy for human review.
 */
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const { createRequire } = require("module");
const { pathToFileURL } = require("url");

const GH = path.resolve(__dirname, "..", "..");
const CANONICAL = path.join(GH, "Ondial_Webhook", "lib", "countryPricing.js");
const HASH_FILE = path.join(GH, "Ondial_Webhook", "docs", "PRICING_MODULE_CANONICAL_HASH.txt");

const COPIES = [
    {
        name: "webhook",
        file: CANONICAL,
        kind: "cjs",
    },
    {
        name: "cs1",
        file: path.join(GH, "Calling_system1", "shared-lib", "src", "countryPricing.js"),
        kind: "esm",
    },
    {
        name: "ondial",
        file: path.join(GH, "Ondial", "lib", "pricing", "countryPricing.js"),
        kind: "esm",
    },
    {
        name: "sa",
        file: path.join(GH, "Ondial-Super-Admin", "lib", "pricing", "countryPricing.js"),
        kind: "esm",
    },
];

async function loadModule(entry) {
    if (entry.kind === "cjs") {
        const req = createRequire(__filename);
        // Bust require cache
        delete req.cache[req.resolve(entry.file)];
        return req(entry.file);
    }
    const url = pathToFileURL(entry.file).href + `?t=${Date.now()}`;
    return import(url);
}

function seedHash(mod) {
    const seed = mod.DEFAULT_COUNTRY_PRICING;
    const fallback = mod.DEFAULT_FALLBACK_ORDER || seed?.fallbackOrder;
    const payload = JSON.stringify({ fallbackOrder: fallback, countries: seed?.countries });
    return {
        sha256: crypto.createHash("sha256").update(payload).digest("hex"),
        payload,
    };
}

function fileHash(filePath) {
    const buf = fs.readFileSync(filePath);
    return crypto.createHash("sha256").update(buf).digest("hex");
}

async function main() {
    const apply = process.argv.includes("--apply");
    const checkCi = process.argv.includes("--check-ci") || !apply;

    const loaded = [];
    for (const c of COPIES) {
        if (!fs.existsSync(c.file)) {
            console.error(`MISSING ${c.name}: ${c.file}`);
            process.exit(1);
        }
        const mod = await loadModule(c);
        const { sha256, payload } = seedHash(mod);
        loaded.push({
            ...c,
            seedSha: sha256,
            fileSha: fileHash(c.file),
            fallback: mod.DEFAULT_FALLBACK_ORDER || mod.DEFAULT_COUNTRY_PRICING?.fallbackOrder,
            payload,
        });
        console.log(`${c.name}: seed=${sha256.slice(0, 12)}… file=${fileHash(c.file).slice(0, 12)}… fallback=${JSON.stringify(mod.DEFAULT_FALLBACK_ORDER || mod.DEFAULT_COUNTRY_PRICING?.fallbackOrder)}`);
    }

    const canon = loaded.find((x) => x.name === "webhook");
    const diffs = loaded.filter((x) => x.seedSha !== canon.seedSha);
    if (diffs.length) {
        console.error("SEED DRIFT vs webhook canonical:");
        for (const d of diffs) {
            console.error(`  - ${d.name} seedSha=${d.seedSha}`);
        }
        if (checkCi && !apply) process.exit(1);
    } else {
        console.log("All DEFAULT_COUNTRY_PRICING seeds MATCH webhook canonical.");
    }

    if (apply) {
        fs.mkdirSync(path.dirname(HASH_FILE), { recursive: true });
        const body = [
            `# Generated by scripts/sync-pricing-module.js`,
            `SEED_SHA256=${canon.seedSha}`,
            `FILE_SHA256=${canon.fileSha}`,
            `DEFAULT_FALLBACK_ORDER=${JSON.stringify(canon.fallback)}`,
            `generatedAt=${new Date().toISOString()}`,
            "",
        ].join("\n");
        fs.writeFileSync(HASH_FILE, body, "utf8");
        // Snapshot for review (not imported at runtime)
        for (const row of loaded) {
            const snap = path.join(path.dirname(row.file), "countryPricing.seed.snapshot.json");
            fs.writeFileSync(snap, row.payload, "utf8");
            console.log(`Wrote snapshot ${snap}`);
        }
        console.log(`Wrote ${HASH_FILE}`);
    }

    // Print cell disagreements count for golden consumers
    console.log(
        JSON.stringify(
            {
                seedParityOk: diffs.length === 0,
                canonicalSeedSha: canon.seedSha,
                disagreeingRepos: diffs.map((d) => d.name),
            },
            null,
            2
        )
    );
}

main().catch((err) => {
    console.error(err);
    process.exit(1);
});
